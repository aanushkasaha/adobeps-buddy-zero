import json
import sys

import checker
import explain
import plan


def main() -> int:
    # 1. Load data
    kb, targets, profile = checker.load_data()

    # 2. Build plan
    p = plan.build_plan(kb, targets, profile)

    # 3. Check plan
    violations = checker.check_plan(p, kb, targets, profile)
    if violations:
        print("Plan validation failed with the following violations:", file=sys.stdout)
        for v in violations:
            print(f"  - {v}", file=sys.stdout)
        return 1

    # 4. Explain plan (only called if 0 violations)
    explanations = explain.explain_plan(p, kb, targets, profile)

    # 5. Print plan details in plan order
    target_map = {t["id"]: t for t in targets.get("targets", [])}
    exp_map = {e["target_id"]: e for e in explanations}

    print("=== Study Plan Items ===")
    for item in p.get("items", []):
        tid = item["target_id"]
        order = item.get("order")
        t_data = target_map.get(tid, {})
        title = t_data.get("title", tid)
        est_hours = t_data.get("est_hours", 0)
        exp_data = exp_map.get(tid, {})
        why = exp_data.get("why", "")
        source = exp_data.get("source", "template")
        print(f"{order}. [{tid}] {title} ({est_hours}h) [{source}] - {why}")

    skipped = p.get("skipped", [])
    if skipped:
        print("\n=== Skipped Targets ===")
        for sid in skipped:
            exp_data = exp_map.get(sid, {})
            why = exp_data.get("why", "")
            print(f"- [{sid}] {why}")

    deferred = p.get("deferred", [])
    if deferred:
        print("\n=== Deferred Targets ===")
        for did in deferred:
            exp_data = exp_map.get(did, {})
            why = exp_data.get("why", "")
            print(f"- [{did}] {why}")

    # 6. Print total est_hours of items and budget
    total_est_hours = sum(
        target_map[item["target_id"]].get("est_hours", 0)
        for item in p.get("items", [])
        if item.get("target_id") in target_map
    )
    constants = targets.get("constants", {})
    cap = constants.get("weekly_study_cap_hours", 0)
    horizon = constants.get("horizon_weeks", 0)
    budget = cap * horizon

    print(f"\nTotal estimated hours: {total_est_hours}h / Budget: {budget}h ({cap}h/week * {horizon} weeks)")

    # 7. Save plan and explanations to last_plan.json
    last_plan_data = {
        "plan": p,
        "explanations": explanations,
    }
    with open("last_plan.json", "w", encoding="utf-8") as f:
        json.dump(last_plan_data, f, indent=2)

    # 8. Print LLM vs template explanation counts
    llm_count = sum(1 for e in explanations if e.get("source") == "llm")
    template_count = sum(1 for e in explanations if e.get("source") == "template")
    print(f"\nExplanations summary: {llm_count} generated by LLM, {template_count} generated by template.")

    return 0


if __name__ == "__main__":
    sys.exit(main())
